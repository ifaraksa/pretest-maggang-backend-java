-- Skema awal aplikasi e-commerce (lihat docs/02-design-modules.md)

-- Modul catalog
CREATE TABLE toko (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        VARCHAR(150) NOT NULL,
    deskripsi   TEXT,
    kota        VARCHAR(100),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE barang (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    toko_id     BIGINT NOT NULL REFERENCES toko (id),
    nama        VARCHAR(200) NOT NULL,
    deskripsi   TEXT,
    harga       NUMERIC(15, 2) NOT NULL CHECK (harga >= 0),
    stok        INTEGER NOT NULL CHECK (stok >= 0),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_barang_toko_id ON barang (toko_id);
CREATE INDEX idx_barang_nama ON barang (nama);

-- Data pelanggan (dasar, tanpa autentikasi)
CREATE TABLE pelanggan (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama        VARCHAR(150) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    no_telepon  VARCHAR(20),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Modul cart
CREATE TABLE keranjang (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pelanggan_id  BIGINT NOT NULL UNIQUE REFERENCES pelanggan (id),
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE item_keranjang (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keranjang_id  BIGINT NOT NULL REFERENCES keranjang (id) ON DELETE CASCADE,
    barang_id     BIGINT NOT NULL REFERENCES barang (id),
    jumlah        INTEGER NOT NULL CHECK (jumlah > 0),
    CONSTRAINT uq_item_keranjang UNIQUE (keranjang_id, barang_id)
);

-- Modul transaction
CREATE TABLE transaksi (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_transaksi  VARCHAR(50) NOT NULL UNIQUE,
    pelanggan_id    BIGINT NOT NULL REFERENCES pelanggan (id),
    total_harga     NUMERIC(15, 2) NOT NULL CHECK (total_harga >= 0),
    status          VARCHAR(20) NOT NULL
                    CHECK (status IN ('DIPROSES', 'SELESAI', 'DIBATALKAN')),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_transaksi_pelanggan_id ON transaksi (pelanggan_id);

CREATE TABLE detail_transaksi (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaksi_id  BIGINT NOT NULL REFERENCES transaksi (id),
    barang_id     BIGINT NOT NULL REFERENCES barang (id),
    nama_barang   VARCHAR(200) NOT NULL,
    harga_satuan  NUMERIC(15, 2) NOT NULL CHECK (harga_satuan >= 0),
    jumlah        INTEGER NOT NULL CHECK (jumlah > 0),
    subtotal      NUMERIC(15, 2) NOT NULL CHECK (subtotal >= 0)
);

CREATE INDEX idx_detail_transaksi_transaksi_id ON detail_transaksi (transaksi_id);
